const CUR = { fr: 'MAD', ar: 'درهم', en: 'MAD' };
export function PRICE(value, lang) {
  const L = lang || 'fr';
  if (value === null || value === undefined || value === '' || value === 0) return ONREQUEST[L] || ONREQUEST.fr;
  if (typeof value === 'string') {
    if (/sur demande/i.test(value)) return ONREQUEST[L] || value;
    return value;
  }
  const n = Number(value);
  if (!isFinite(n) || n <= 0) return ONREQUEST[L] || ONREQUEST.fr;
  return n.toLocaleString('fr-FR') + ' ' + (CUR[L] || 'MAD');
}

